import { StatusBadge } from '../../../../shared/components/StatusBadge.jsx'

const screenshotUrl = (runId, resultId, variant) =>
  `/api/runs/${runId}/screenshots/${resultId}?variant=${variant}`

function ScreenshotLinks({ runId, result }) {
  const failureLabel = result.status === 'healed' ? 'Before' : 'Failure'
  return (
    <span className="screenshot-links">
      {result.screenshotPath && (
        <a
          href={screenshotUrl(runId, result.id, 'failure')}
          target="_blank"
          rel="noreferrer"
        >
          {failureLabel}
        </a>
      )}
      {result.afterScreenshotPath && (
        <a href={screenshotUrl(runId, result.id, 'after')} target="_blank" rel="noreferrer">
          After
        </a>
      )}
      {!result.screenshotPath && '—'}
    </span>
  )
}

function ResultDetails({ runId, result }) {
  return (
    <details className="result-details">
      <summary>Criterion, generated spec and screenshots</summary>
      <p className="detail-line">
        <span className="repair-label">Criterion</span>
        {result.criterion}
      </p>
      <p className="detail-line">
        <span className="repair-label">Generated by</span>
        {result.generatedBy.toUpperCase()}
        {result.generationNote && <span className="detail-muted"> · {result.generationNote}</span>}
      </p>
      <p className="detail-line">
        <span className="repair-label">Attempts</span>
        {result.attempts.map((attempt) => attempt.toUpperCase()).join(' / ')}
      </p>
      <pre className="spec-code">{result.specCode}</pre>
      {result.afterScreenshotPath && (
        <div className="screenshot-compare">
          <figure>
            <figcaption>Before heal</figcaption>
            <img
              src={screenshotUrl(runId, result.id, 'failure')}
              alt={`Before heal: ${result.testName}`}
            />
          </figure>
          <figure>
            <figcaption>After heal</figcaption>
            <img
              src={screenshotUrl(runId, result.id, 'after')}
              alt={`After heal: ${result.testName}`}
            />
          </figure>
        </div>
      )}
      {result.status === 'failed' && result.screenshotPath && (
        <figure className="single-screenshot">
          <figcaption>At failure</figcaption>
          <img
            src={screenshotUrl(runId, result.id, 'failure')}
            alt={`Failure: ${result.testName}`}
          />
        </figure>
      )}
    </details>
  )
}

function ResultsTable({ run }) {
  const counts = run.results.reduce(
    (tally, result) => ({ ...tally, [result.status]: (tally[result.status] ?? 0) + 1 }),
    {},
  )
  const generators = [
    ...new Set(run.results.map((result) => result.generatedBy.toUpperCase())),
  ].join(' + ')

  return (
    <section className="results-section">
      <h2>Test Results</h2>
      <p className="results-summary">
        {run.ticketId} on {run.siteUrl ?? run.siteName} · {counts.passed ?? 0} passed ·{' '}
        {counts.healed ?? 0} healed · {counts.failed ?? 0} failed · written by {generators || '—'} ·
        {' '}suite {run.suiteSource ?? 'unknown'} · {run.repeatCount} run(s) per test
      </p>
      {run.results.length === 0 && <p className="empty">No test results recorded</p>}
      <table className="results-table">
        <thead>
          <tr>
            <th>Test</th>
            <th>Status</th>
            <th>Duration</th>
            <th>Error</th>
            <th>Screenshot</th>
          </tr>
        </thead>
        {run.results.map((result) => (
          <tbody key={result.id} className={`result-group ${result.status}`}>
            <tr>
              <td>{result.testName}</td>
              <td className="status-cell">
                <StatusBadge status={result.status} />
                {result.flaky && <StatusBadge status="flaky" />}
              </td>
              <td>{result.duration}ms</td>
              <td className={result.errorMessage ? 'error-cell' : ''}>
                {result.errorMessage ?? result.screenshotWarning ?? '—'}
              </td>
              <td>
                <ScreenshotLinks runId={run.id} result={result} />
              </td>
            </tr>
            <tr className="details-row">
              <td colSpan={5}>
                <ResultDetails runId={run.id} result={result} />
              </td>
            </tr>
          </tbody>
        ))}
      </table>
    </section>
  )
}

export { ResultsTable }
